import Foundation

@MainActor func archiveMatchingTest() throws {
    let paperless = Project(path:"/archive/paperless",name:"53-2023年至2025年（24个月）黔南独山县机关事务服务中心无纸化办公系统项目")
    let office = Project(path:"/archive/office",name:"6月 地震大数据贵州中心非通用办公设备、资产采购")
    let industry = Project(path:"/archive/industry",name:"4 2025省工业和信息化厅云上统筹云安全保障服务")
    let government = Project(path:"/archive/government",name:"4月 贵州省民宗委2026年贵州省政务信息化运维项目比选文件（本地安全设备）")
    let extensionOnly = Project(path:"/archive/extension",name:"已解决的 docx 类")
    let fuel = Project(path:"/archive/fuel",name:"惠水加油站")
    let paperlessFile = BrowserRow(id:"/inbox/paperless.docx",title:"法律意见书暨仲裁预案-无纸化办公.docx")
    let index = ArchiveProjectIndex(projects:[office,industry,government,paperless,extensionOnly,fuel])
    let screenshot = index.recommendations(for:[paperlessFile],token:IndexCancellation())
    try verify(screenshot.map(\.id) == [paperless.path,office.path] && screenshot.map(\.score) == [5,2],"The screenshot retains only the five-character and two-character runs, ignoring isolated characters and the extension")
    try verify(screenshot.first?.matchingRanges.map { String(paperless.name[$0]) } == ["无纸化办公"],"The five-character run is highlighted in the original project title")
    try verify(screenshot.last?.matchingRanges.map { String(office.name[$0]) } == ["办公"],"Only the matching portion of the partial project is highlighted")
    try verify(index.search("惠水").map(\.path) == [fuel.path],"An unrelated destination remains accessible through manual search")

    let continuous = Project(path:"/archive/continuous",name:"甲乙丙丁")
    let fragmented = Project(path:"/archive/fragmented",name:"甲乙丙、丁戊己、庚辛")
    let partial = Project(path:"/archive/partial",name:"甲乙丙、丁、戊")
    let reversed = Project(path:"/archive/reversed",name:"辛庚己戊丁丙乙甲")
    let scattered = Project(path:"/archive/scattered",name:"甲-乙-丙-丁")
    let keywordOnly = Project(path:"/archive/keyword",name:"财务资料",keywords:"甲乙丙丁")
    let orderIndex = ArchiveProjectIndex(projects:[fragmented,partial,reversed,scattered,continuous,keywordOnly])
    let sequence = BrowserRow(id:"/inbox/sequence.pdf",title:"甲乙丙丁戊己庚辛.pdf")
    let ranks = orderIndex.recommendations(for:[sequence],token:IndexCancellation())
    try verify(ranks.map(\.id) == [continuous.path,fragmented.path,partial.path] && ranks.map(\.score) == [4,8,3],"The longest run sorts before total coverage, and isolated characters do not boost scores")
    try verify(ranks.last?.matchingRanges.map { String(partial.name[$0]) } == ["甲乙丙"],"Isolated matches beside a valid run remain unmarked")
    try verify(orderIndex.search("甲乙丙丁").contains { $0.path == keywordOnly.path },"Manual search still accepts configured keywords")

    let separated = BrowserRow(id:"/inbox/separated.pdf",title:"甲—乙.pdf")
    try verify(orderIndex.recommendations(for:[separated],token:IndexCancellation()).isEmpty,"Punctuation in filenames does not connect isolated characters")
    let singles = [BrowserRow(id:"/inbox/a.txt",title:"甲.txt"),BrowserRow(id:"/inbox/b.txt",title:"乙.txt")]
    try verify(orderIndex.recommendations(for:singles,token:IndexCancellation()).isEmpty,"Characters from different source files cannot form a run")

    let repeated = Project(path:"/archive/repeated",name:"办公办公")
    let plain = Project(path:"/archive/plain",name:"办公")
    let coded = Project(path:"/archive/coded",name:"A2046")
    let batchIndex = ArchiveProjectIndex(projects:[repeated,plain,coded])
    let officeFile = BrowserRow(id:"/inbox/office",title:"办公.txt")
    try verify(batchIndex.recommendations(for:[officeFile],token:IndexCancellation()).map(\.score) == [2,2],"Repeated appearances of one filename run cannot inflate its score")
    let folder = BrowserRow(id:"/inbox/folder",title:"文件.ａ２０４６",folder:true)
    let combined = batchIndex.recommendations(for:[officeFile,folder],token:IndexCancellation())
    try verify(combined.first?.id == coded.path && combined.first?.matchingRanges.map { String(coded.name[$0]) } == ["A2046"],"Batch matching preserves case/width normalization and folder text after a dot")
    let cancelled = IndexCancellation(); cancelled.cancel()
    try verify(batchIndex.recommendations(for:[officeFile],token:cancelled).isEmpty,"Cancellation prevents publication of matches")
    print("PASS: archive continuous runs, longest-first ranking, isolated character and extension exclusion, highlight spans, repeats, batch matching and manual search")
}
