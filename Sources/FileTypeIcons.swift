    private static let suffixes = mapping.keys.sorted { $0.count > $1.count }
    private static let bundles: Set<String> = ["app", "pages", "numbers", "key", "mindnode"]
    public static func iconID(for filename: String, isDirectory: Bool = false, isAlias: Bool = false) -> String? {
        if isAlias { return "shortcut" }
        let name = filename.replacingOccurrences(of: "\\", with: "/").split(separator: "/", omittingEmptySubsequences: false).last.map(String.init)?.lowercased() ?? ""
        if isDirectory && !bundles.contains(where: { name.hasSuffix("." + $0) }) { return nil }
        return suffixes.first(where: { name.hasSuffix("." + $0) }).flatMap { mapping[$0] } ?? "unknown"
    }
    public static func assetName(for url: URL, isDirectory: Bool = false, isAlias: Bool = false) -> String? {
        iconID(for: url.lastPathComponent, isDirectory: isDirectory, isAlias: isAlias).map { "file-type-" + $0 }
    }
